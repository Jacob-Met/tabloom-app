import {mkdir,copyFile,readdir,readFile,writeFile,rm} from "node:fs/promises";
import {fileURLToPath} from "node:url";
import {dirname,resolve,join} from "node:path";
const root=resolve(dirname(fileURLToPath(import.meta.url)),"..");
const output=join(root,"tabloom","receipt-ocr");
const packagePath=name=>join(root,"node_modules",name);
await rm(output,{recursive:true,force:true});
await mkdir(join(output,"core"),{recursive:true});
await mkdir(join(output,"lang"),{recursive:true});
for(const name of ["tesseract.min.js","worker.min.js"])await copyFile(join(packagePath("tesseract.js"),"dist",name),join(output,name));
const cores=(await readdir(packagePath("tesseract.js-core"))).filter(name=>/^tesseract-core.*\.wasm\.js$/.test(name));
if(cores.length!==6)throw Error("Unexpected OCR core assets; review the static allowlist.");
for(const name of cores)await copyFile(join(packagePath("tesseract.js-core"),name),join(output,"core",name));
await copyFile(join(packagePath("@tesseract.js-data/eng"),"4.0.0_best_int","eng.traineddata.gz"),join(output,"lang","eng.traineddata.gz"));
await copyFile(join(packagePath("tesseract.js"),"LICENSE.md"),join(output,"LICENSE-tesseract.js"));
await copyFile(join(packagePath("tesseract.js-core"),"LICENSE"),join(output,"LICENSE-tesseract.js-core"));
const versions={};
for(const name of ["tesseract.js","tesseract.js-core","@tesseract.js-data/eng"])versions[name]=JSON.parse(await readFile(join(packagePath(name),"package.json"),"utf8")).version;
await writeFile(join(output,"ABOUT.txt"),"Local English OCR. Tesseract.js, Tesseract core and English traineddata: Apache-2.0.\nhttps://github.com/naptha/tesseract.js\nhttps://github.com/naptha/tessdata\n"+JSON.stringify(versions,null,2)+"\n");
console.log("Prepared local receipt reader",versions);
